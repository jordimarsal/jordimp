"""Citation policy: only retrieved chunks can be cited; honest not-covered copy."""

import re
from collections.abc import Sequence
from dataclasses import dataclass

from ask_api.config import Lang
from ask_api.ports import ScoredChunk
from ask_api.result import CitationMissing, Err, Ok, Result

_MARKER_RE = re.compile(r"\[(\d{1,3})\]")
_INLINE_SPACES_RE = re.compile(r"[ \t]{2,}")
_ORPHAN_PUNCT_RE = re.compile(r"[ \t]+([.,;:!?])")

_NOT_COVERED: dict[Lang, str] = {
    "en": (
        "That is not in the available profile — the public CV and portfolio cover "
        "projects, stack and roles described on jordimp.net. Try asking about those."
    ),
    "es": (
        "Eso no consta en el perfil disponible — el CV público y el portafolio cubren "
        "proyectos, stack y roles descritos en jordimp.net. Prueba preguntando por eso."
    ),
    "ca": (
        "Això no consta en el perfil disponible — el CV públic i el portafoli cobreixen "
        "projectes, stack i rols descrits a jordimp.net. Prova de preguntar per això."
    ),
}


def not_covered_text(lang: Lang) -> str:
    """The honest refusal copy for a language — never generated by the model."""
    return _NOT_COVERED[lang]


def _normalize(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip().casefold()


@dataclass(frozen=True)
class Citation:
    source: str
    title: str
    heading: str


def enforce(
    text: str, chunks: Sequence[ScoredChunk], lang: Lang
) -> Result[tuple[str, tuple[Citation, ...]], CitationMissing]:
    """Keep only markers referencing retrieved chunks; strip the rest.

    Returns `Err(CitationMissing)` when no valid citation remains, or when the
    model echoed the not-covered copy (even with a citation appended) — the
    caller turns both into the not-covered response.
    """
    used: dict[int, None] = {}
    total = len(chunks)

    def replace(match: re.Match[str]) -> str:
        index = int(match.group(1))
        if 1 <= index <= total:
            used[index] = None
            return match.group(0)
        return ""

    cleaned = _MARKER_RE.sub(replace, text)
    cleaned = _INLINE_SPACES_RE.sub(" ", cleaned)
    cleaned = _ORPHAN_PUNCT_RE.sub(r"\1", cleaned).strip()
    if _normalize(not_covered_text(lang)) in _normalize(cleaned):
        return Err(CitationMissing())
    if not used:
        return Err(CitationMissing())
    citations = tuple(
        Citation(
            source=chunks[index - 1].chunk.source,
            title=chunks[index - 1].chunk.title,
            heading=chunks[index - 1].chunk.heading,
        )
        for index in used
    )
    return Ok((cleaned, citations))
